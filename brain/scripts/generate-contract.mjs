import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(scriptDir, "..", "..");
const schemaPath = resolve(repoRoot, "protocol", "schema", "protocol.schema.json");
const policyPath = resolve(repoRoot, "config", "v0.1-policy.json");
const tsPath = resolve(repoRoot, "brain", "src", "generated", "contract-constants.ts");
const schemaTsPath = resolve(repoRoot, "brain", "src", "generated", "protocol-schema.ts");
const javaPath = resolve(
  repoRoot,
  "minecraft",
  "common",
  "src",
  "main",
  "java",
  "io",
  "github",
  "kardane",
  "jarvisminecraft",
  "common",
  "generated",
  "GeneratedContractConstants.java",
);

const readJson = async (path) => JSON.parse(await readFile(path, "utf8"));

const schema = await readJson(schemaPath);
const policy = await readJson(policyPath);

const protocolVersion =
  schema?.$defs?.envelopeBase?.properties?.protocolVersion?.const;
const limitProperties =
  schema?.$defs?.capabilitiesMessage?.allOf?.[1]?.properties?.payload
    ?.properties?.limits?.properties;
const maxMessageBytes = limitProperties?.maxMessageBytes?.const;
const maxToolCallsPerRequest = limitProperties?.maxToolCallsPerRequest?.const;
const maxModelRoundTripsPerRequest =
  limitProperties?.maxModelRoundTripsPerRequest?.const;
const sessionTtlMs = policy?.runtime?.sessionTtlMs;
const requestDeadlineMs = policy?.runtime?.requestDeadlineMs;

requireString(protocolVersion, "protocolVersion");
requirePositiveInteger(maxMessageBytes, "maxMessageBytes");
requirePositiveInteger(maxToolCallsPerRequest, "maxToolCallsPerRequest");
requirePositiveInteger(maxModelRoundTripsPerRequest, "maxModelRoundTripsPerRequest");
requirePositiveInteger(sessionTtlMs, "sessionTtlMs");
requirePositiveInteger(requestDeadlineMs, "requestDeadlineMs");

const ts = `// Generated by brain/scripts/generate-contract.mjs. Do not edit by hand.

export const PROTOCOL_VERSION = ${JSON.stringify(protocolVersion)} as const;

export const PROTOCOL_LIMITS = {
  maxMessageBytes: ${maxMessageBytes},
  maxToolCallsPerRequest: ${maxToolCallsPerRequest},
  maxModelRoundTripsPerRequest: ${maxModelRoundTripsPerRequest},
} as const;

export const RUNTIME_POLICY = {
  sessionTtlMs: ${sessionTtlMs},
  requestDeadlineMs: ${requestDeadlineMs},
} as const;
`;

const schemaTs = `// Generated by brain/scripts/generate-contract.mjs. Do not edit by hand.

export const PROTOCOL_SCHEMA = ${JSON.stringify(schema, null, 2)} as const;
`;

const java = `package io.github.kardane.jarvisminecraft.common.generated;

/**
 * Generated by brain/scripts/generate-contract.mjs.
 * Source of truth: protocol/schema/protocol.schema.json and config/v0.1-policy.json.
 */
public final class GeneratedContractConstants {
    public static final String PROTOCOL_VERSION = ${JSON.stringify(protocolVersion)};
    public static final int MAX_MESSAGE_BYTES = ${javaNumber(maxMessageBytes)};
    public static final int MAX_TOOL_CALLS_PER_REQUEST = ${javaNumber(maxToolCallsPerRequest)};
    public static final int MAX_MODEL_ROUND_TRIPS_PER_REQUEST = ${javaNumber(maxModelRoundTripsPerRequest)};
    public static final long SESSION_TTL_MILLIS = ${javaNumber(sessionTtlMs)}L;
    public static final long REQUEST_DEADLINE_MILLIS = ${javaNumber(requestDeadlineMs)}L;

    private GeneratedContractConstants() {
    }
}
`;

const mode = process.argv[2] ?? "--write";
if (mode === "--check") {
  await assertGenerated(tsPath, ts);
  await assertGenerated(schemaTsPath, schemaTs);
  await assertGenerated(javaPath, java);
  console.log("Generated contract artifacts are up to date.");
} else if (mode === "--write") {
  await writeFile(tsPath, ts, "utf8");
  await writeFile(schemaTsPath, schemaTs, "utf8");
  await writeFile(javaPath, java, "utf8");
  console.log("Generated contract artifacts updated.");
} else {
  throw new Error("Usage: node generate-contract.mjs [--write|--check]");
}

async function assertGenerated(path, expected) {
  const actual = await readFile(path, "utf8");
  if (actual !== expected) {
    throw new Error(
      path + " is stale. Run `npm run generate:contract` from brain/ and commit the result.",
    );
  }
}

function requireString(value, name) {
  if (typeof value !== "string" || value.length === 0) {
    throw new Error(name + " must be a non-empty string.");
  }
}

function requirePositiveInteger(value, name) {
  if (!Number.isSafeInteger(value) || value < 1) {
    throw new Error(name + " must be a positive integer.");
  }
}

function javaNumber(value) {
  return String(value).replace(/\B(?=(\d{3})+(?!\d))/g, "_");
}
